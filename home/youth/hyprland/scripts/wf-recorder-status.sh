#!/usr/bin/env bash
# ============================================================================
# wf-recorder-status.sh —— 录屏状态检测
# ----------------------------------------------------------------------------
# 被 Waybar 的 custom/wf-recorder 模块每 2 秒轮询一次（见 ../waybar.nix），
# 用于在状态栏显示当前是否有录屏任务正在运行。
#
# 实现方式：检查 PID 文件是否存在，且对应进程是否存活。
#   - 录制中：输出 JSON，text 为红色 REC，状态栏显示录制提示
#   - 未录制：输出空字符串，配合 Waybar 的 hide-empty-text = true 完全隐藏
#
# 依赖：录屏脚本在启动 wf-recorder 时把进程号写入 PIDFILE
#       （见同目录的截图录屏脚本 capture.sh）。
#
# 安装位置：~/.config/waybar/scripts/wf-recorder-status.sh
#           （由 scripts/default.nix 中的 home.file 声明并设置可执行权限）
# ============================================================================

# 严格模式：命令出错立即退出、未定义变量报错、管道失败即失败
set -euo pipefail

# ---------------------------------------------------------------------------
# PID 文件路径（由录屏脚本在启动时创建）
# ---------------------------------------------------------------------------
PIDFILE=/tmp/wf-recorder.pid

# ---------------------------------------------------------------------------
# 状态判断
# 说明：kill -0 只发送探测信号，不会真正杀死进程，
#       因此可用来安全地判断目标进程是否存活。
# ---------------------------------------------------------------------------
if [ -f "$PIDFILE" ] && kill -0 $(cat "$PIDFILE") 2>/dev/null; then
    # 正在录制：输出 Waybar 需要的 JSON（text 显示在栏上，tooltip 为悬浮提示）
    echo "{\"text\":\"🔴REC\",\"tooltip\":\"录制中\"}"
else
    # 未录制：输出空内容，Waybar 的 hide-empty-text 会隐藏该模块
    echo ""
fi

